package me.yuugao.robomatch.domain;

/**
 * Статус проекта: draft / active / archived.
 * <p>
 * Жизненный цикл проекта не задан - минимальный набор выбран
 * командой (assumptions.md §18): черновик только что создан, активен -
 * прошёл расчёт/используется, в архиве - скрыт из основной выборки.
 * Логика переключения статусов - на уровне приложения;
 * проекты создаются со статусом draft.
 */
public enum ProjectStatus {
    /**
 * Черновик: только что создан, расчётов может не быть.
 */
    DRAFT,
    /**
 * Активен: прошёл расчёт / используется.
 */
    ACTIVE,
    /**
 * В архиве: скрыт из основной выборки.
 */
    ARCHIVED
}
