package me.yuugao.robomatch.domain;

/**
 * Роль пользователя: гость / пользователь / админ.
 * <p>
 * В БД роль хранится строкой в нижнем регистре (V1__baseline_schema.sql,
 * CHECK (role IN ('guest', 'user', 'admin'))); в Spring Security превращается
 * в authority «ROLE_&lt;ИМЯ&gt;» (ROLE_USER, ROLE_ADMIN) — см. JwtAuthFilter.
 * <p>
 * Гость — не строка в таблице user, а отсутствие аутентификации: гость
 * просто не имеет JWT (requirements/roles.md: каталог и демо-расчёт без
 * сохранения данных). Регистрация всегда создаёт роль USER; ADMIN выдаёт
 * только seed демо-аккаунта — повышать себя через API нельзя.
 */
public enum UserRole {
    /**
 * Гость — не строка в БД: отсутствие аутентификации; каталог и демо-расчёт без сохранения.
 */
    GUEST,
    /**
 * Зарегистрированный пользователь: свои проекты, параметры, расчёты и выгрузки.
 */
    USER,
    /**
 * Администратор: справочники и импорт каталога.
 */
    ADMIN
}
