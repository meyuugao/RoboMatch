-- V6: точность ROI (numeric(7,2) -> numeric(12,2)).
--
-- Почему: ревью задачи B (находка EE-2/ER-4, 2026-09-23): roi_pct
-- numeric(7,2) переполняется при |ROI| >= 100 000 % — достижимо на
-- живых данных (RaaS с выкупом + горизонт 10 лет даёт ~150 000 %);
-- INSERT падал бы 500/409 с неверным диагнозом. numeric(12,2)
-- покрывает до 9 999 999 999.99 %; свыше — cap движка (null +
-- предупреждение, по образцу Payback, ревью VR-5). Данные не меняются.
ALTER TABLE calculation ALTER COLUMN roi_pct TYPE numeric(12,2);
