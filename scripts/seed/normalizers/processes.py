"""Разрезание поля «Сценарий» на процессы.

data_model.md §5.3: разрез по «, » с картой исключений; trim; карта опечаток.
"""
from collections.abc import Callable
from typing import TypeAlias

from .strings import norm_text

LogFn: TypeAlias = Callable[[str], None]

# Значения, где «, » находится ВНУТРИ названия одного процесса: разрез даёт
# обрывки, не являющиеся самостоятельными процессами («...труднодоступные
# районы», «воздушного лазерного сканирования и тепловизионной съемки»).
# Выявлены сплошным просмотром 98 уникальных значений поля «Сценарий».
# Подтвердить у организатора (см. README, «Риски»).
SCENARIO_EXCEPTIONS: frozenset[str] = frozenset({
    "Доставка в удаленные, труднодоступные районы",
    "Мониторинг, патрулирование, перевозка грузов",
    "Выполнение контрольных мероприятий на этапе строительно-монтажных работ "
    "с использованием фотограмметрии, воздушного лазерного сканирования и тепловизионной съемки",
})

# Карта опечаток - assumptions.md §10 (ведётся в этом документе).
# «Доставка биоматериаловм» - задокументированная опечатка организатора.
TYPO_FIXES: dict[str, str] = {
    "Доставка биоматериаловм": "Доставка биоматериалов",
}


def split_scenarios(raw, log: LogFn | None = None) -> list[str]:
    """Одно значение CSV -> список имён процессов (нормализованных)."""
    s = norm_text(raw)
    if s is None:
        return []
    fixed = TYPO_FIXES.get(s)
    if fixed is not None:
        if log:
            log(f"опечатка исправлена (assumptions.md §10): «{s}» -> «{fixed}»")
        s = fixed
    if s in SCENARIO_EXCEPTIONS:
        if log:
            log(f"сценарий не разрезается (запятая внутри названия): «{s[:70]}…»")
        return [s]
    return [part for part in (p.strip() for p in s.split(", ")) if part]
